import { mkdir, rm } from "node:fs/promises";
import { join } from "node:path";

// Bundle the React hub UI into the two static files that src/hub/server.ts embeds as text.
const outputs = { js: "src/hub/assets/hub.js", css: "src/hub/assets/hub.css" } as const;
const banner = "Generated by bun run hub:build from src/hub/web. Do not edit.";
const temporary = join("node_modules", ".cache", `hub-${process.pid}-${crypto.randomUUID()}`);
await mkdir(temporary, { recursive: true });
try {
  const result = await Bun.build({
    entrypoints: ["src/hub/web/main.tsx"],
    target: "browser",
    format: "esm",
    minify: true,
    define: { "process.env.NODE_ENV": JSON.stringify("production") },
    outdir: temporary,
    naming: { entry: "hub.[ext]", asset: "hub.[ext]" },
  });
  if (!result.success) {
    throw new Error(`Hub bundle failed:\n${result.logs.map((log) => log.message).join("\n")}`);
  }
  const find = (extension: string) => {
    const matches = result.outputs.filter((output) => output.path.endsWith(extension));
    if (matches.length !== 1) throw new Error(`Expected one ${extension} hub artifact`);
    return matches[0] as Bun.BuildArtifact;
  };
  const expected = {
    js: `// ${banner}\n${await find(".js").text()}`,
    css: `/* ${banner} */\n${await find(".css").text()}`,
  };
  for (const kind of ["js", "css"] as const) {
    if (process.argv.includes("--check")) {
      // Missing or unreadable generated assets are build errors, not optional inputs.
      const current = await Bun.file(outputs[kind]).text();
      if (current !== expected[kind]) {
        throw new Error(`${outputs[kind]} is stale; run bun run hub:build`);
      }
    } else {
      await Bun.write(outputs[kind], expected[kind]);
    }
  }
} finally {
  await rm(temporary, { recursive: true, force: true });
}
