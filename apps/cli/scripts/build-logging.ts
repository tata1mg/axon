// The launcher imports this module as code; Pi needs the same bytes as an asset.
// Separate paths avoid Bun treating the code import as an opaque file in compiled builds.
const source = "src/logging/process-logger.cjs";
const output = "src/logging/process-logger-preload.cjs";
const expected = `// Generated by bun run logging:build. Do not edit.\n${(await Bun.file(source).text()).trimEnd()}\n`;

if (process.argv.includes("--check")) {
  const current = await Bun.file(output).text();
  if (current.trimEnd() !== expected.trimEnd()) {
    throw new Error("Logging preload is stale; run bun run logging:build");
  }
} else {
  await Bun.write(output, expected);
}
