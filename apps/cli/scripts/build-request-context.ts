import { mkdir, rm } from "node:fs/promises";
import { join } from "node:path";

// Bundle the shared workflow contract so the materialized extension needs no adjacent sources.
const output = "src/harnesses/pi/resources/extensions/request-context.mjs";
const temporary = join(
  "node_modules",
  ".cache",
  `request-context-${process.pid}-${crypto.randomUUID()}`,
);
await mkdir(temporary, { recursive: true });
try {
  const result = await Bun.build({
    entrypoints: ["src/harnesses/pi/resources/extensions/request-context.ts"],
    external: ["@earendil-works/pi-coding-agent"],
    target: "node",
    format: "esm",
    minify: true,
    outdir: temporary,
    naming: "request-context.mjs",
  });
  if (!result.success) {
    throw new Error(
      `Request context extension bundle failed:\n${result.logs.map((log) => log.message).join("\n")}`,
    );
  }
  const artifact = result.outputs[0];
  if (!artifact) throw new Error("Missing request context extension artifact");
  const expected = `// Generated by bun run request-context:build. Do not edit.\n${await artifact.text()}`;
  if (process.argv.includes("--check")) {
    // Missing or unreadable generated assets are build errors, not optional inputs.
    const current = await Bun.file(output).text();
    if (current !== expected) {
      throw new Error("Request context bundle is stale; run bun run request-context:build");
    }
  } else {
    await Bun.write(output, expected);
  }
} finally {
  await rm(temporary, { recursive: true, force: true });
}
